-- Delta Collection database schema.
-- Run this once in Supabase: Dashboard -> SQL Editor -> New query -> paste -> Run.
-- Then run seed.sql to load the 180 products from the price list.

create table if not exists public.categories (
  slug text primary key,
  name text not null,
  "group" text not null default 'face-care',
  sort int not null default 0
);

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  slug text unique not null,
  name text not null,
  brand text,
  category text not null references public.categories(slug) on update cascade,
  price int not null check (price >= 0),
  compare_at_price int,
  size text,
  image text,
  description text,
  in_stock boolean not null default true,
  is_new boolean not null default false,
  tags text[] not null default '{}',
  created_at timestamptz not null default now()
);

create index if not exists products_category_idx on public.products(category);
create index if not exists products_created_idx on public.products(created_at desc);

-- Who may edit: emails listed here (and signed in) can change products.
create table if not exists public.admins (
  email text primary key
);

create or replace function public.is_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.admins where email = auth.jwt() ->> 'email');
$$;

alter table public.categories enable row level security;
alter table public.products enable row level security;
alter table public.admins enable row level security;

drop policy if exists "public read categories" on public.categories;
create policy "public read categories" on public.categories for select using (true);
drop policy if exists "admin write categories" on public.categories;
create policy "admin write categories" on public.categories for all using (public.is_admin()) with check (public.is_admin());

drop policy if exists "public read products" on public.products;
create policy "public read products" on public.products for select using (true);
drop policy if exists "admin write products" on public.products;
create policy "admin write products" on public.products for all using (public.is_admin()) with check (public.is_admin());

-- Product photos: public to view, only admins can upload or delete.
insert into storage.buckets (id, name, public)
values ('product-images', 'product-images', true)
on conflict (id) do nothing;

drop policy if exists "public read product images" on storage.objects;
create policy "public read product images" on storage.objects for select using (bucket_id = 'product-images');
drop policy if exists "admin upload product images" on storage.objects;
create policy "admin upload product images" on storage.objects for insert with check (bucket_id = 'product-images' and public.is_admin());
drop policy if exists "admin change product images" on storage.objects;
create policy "admin change product images" on storage.objects for update using (bucket_id = 'product-images' and public.is_admin());
drop policy if exists "admin delete product images" on storage.objects;
create policy "admin delete product images" on storage.objects for delete using (bucket_id = 'product-images' and public.is_admin());

